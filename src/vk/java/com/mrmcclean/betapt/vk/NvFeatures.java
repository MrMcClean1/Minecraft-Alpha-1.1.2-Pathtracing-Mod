    private static int frameCounter;
    private boolean dlssReady;
    public String dlssStatus = "";

    /** After the Vulkan device is made through Streamline: is DLSS supported on this GPU? */
    boolean dlssAfterDevice(VkPhysicalDevice physical) {
        if (!slStarted) { dlssStatus = status; return false; }
        try {
            adapter = struct(AdapterInfo_SIZE, AdapterInfo_GUID, AdapterInfo_VERSION);
            MemoryUtil.memPutAddress(adapter + AdapterInfo_vkPhysicalDevice, physical.address());
            int r = slIsFeatureSupported.call(FEATURE_DLSS, adapter);
            if (r != RESULT_OK) { dlssStatus = "DLSS isn't supported on this GPU (Streamline result " + r + ")"; return false; }
            try (MemoryStack stack = MemoryStack.stackPush()) {
                PointerBuffer p = stack.callocPointer(1);
                long name = MemoryUtil.memAddress(stack.UTF8("slDLSSSetOptions"));
                r = slGetFeatureFunction.call(FEATURE_DLSS, name, p.address());
                if (r != RESULT_OK || p.get(0) == 0) { dlssStatus = "DLSS: no slDLSSSetOptions (" + r + ")"; return false; }
                slDLSSSetOptions = new Fn(p.get(0), "PP");
                p.put(0, 0);
                name = MemoryUtil.memAddress(stack.UTF8("slDLSSGetOptimalSettings"));
                r = slGetFeatureFunction.call(FEATURE_DLSS, name, p.address());
                if (r != RESULT_OK || p.get(0) == 0) { dlssStatus = "DLSS: no slDLSSGetOptimalSettings (" + r + ")"; return false; }
                slDLSSGetOptimalSettings = new Fn(p.get(0), "PP");
            }
            viewport = struct(ViewportHandle_SIZE, ViewportHandle_GUID, ViewportHandle_VERSION);
            MemoryUtil.memPutInt(viewport + ViewportHandle_value, 0);
            options = struct(DLSSOptions_SIZE, DLSSOptions_GUID, DLSSOptions_VERSION);
            optimal = struct(DLSSOptimalSettings_SIZE, DLSSOptimalSettings_GUID, DLSSOptimalSettings_VERSION);
            constants = struct(Constants_SIZE, Constants_GUID, Constants_VERSION);
            resources = MemoryUtil.nmemCalloc(4, Resource_SIZE);
            tags = MemoryUtil.nmemCalloc(4, ResourceTag_SIZE);
            for (int i = 0; i < 4; i++) {
                long res = resources + (long) i * Resource_SIZE, tag = tags + (long) i * ResourceTag_SIZE;
                for (int k = 0; k < 16; k++) {
                    MemoryUtil.memPutByte(res + BASE_structType + k, Resource_GUID[k]);
                    MemoryUtil.memPutByte(tag + BASE_structType + k, ResourceTag_GUID[k]);
                }
                MemoryUtil.memPutLong(res + BASE_structVersion, Resource_VERSION);
                MemoryUtil.memPutLong(tag + BASE_structVersion, ResourceTag_VERSION);
                MemoryUtil.memPutAddress(tag + ResourceTag_resource, res);
                MemoryUtil.memPutInt(tag + ResourceTag_lifecycle, LIFE_VALID_UNTIL_EVALUATE);
            }
            MemoryUtil.memPutInt(tags + ResourceTag_type, BUF_IN_COLOR);
            MemoryUtil.memPutInt(tags + ResourceTag_SIZE + ResourceTag_type, BUF_DEPTH);
            MemoryUtil.memPutInt(tags + 2L * ResourceTag_SIZE + ResourceTag_type, BUF_MVEC);
            MemoryUtil.memPutInt(tags + 3L * ResourceTag_SIZE + ResourceTag_type, BUF_OUT_COLOR);
            inputs = MemoryUtil.nmemCalloc(1, 8);
            MemoryUtil.memPutAddress(inputs, viewport);
            tokenSlot = MemoryUtil.nmemCalloc(1, 8);
            frameIndex = MemoryUtil.nmemCalloc(1, 4);
            dlssReady = true;
            dlssStatus = "DLSS ready";
            return true;
        } catch (Throwable t) {
            dlssStatus = "DLSS: " + t;
            return false;
        }
    }

