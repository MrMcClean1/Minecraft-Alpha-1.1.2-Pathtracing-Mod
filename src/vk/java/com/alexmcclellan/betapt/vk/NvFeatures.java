    /**
     * Before any Vulkan instance: starts Streamline and makes sl.interposer.dll LWJGL's Vulkan library. Returns false
     * (and leaves Vulkan as it was) if it can't: not Windows, DLLs missing, or Streamline refused.
     */
    static synchronized boolean startStreamline() {
        if (slStarted) return true;
        if (slTried) return false;
        slTried = true;
        try {
            if (!System.getProperty("os.name", "").toLowerCase().contains("win")) { status = "DLSS: Windows only"; return false; }
            File d = dir(), ip = new File(d, "sl.interposer.dll");
            if (!ip.isFile() || !new File(d, "sl.dlss.dll").isFile() || !new File(d, "nvngx_dlss.dll").isFile()) {
                status = "DLSS: the Streamline files aren't in " + d; return false;
            }
            interposer = org.lwjgl.system.APIUtil.apiCreateLibrary(ip.getAbsolutePath());
            slInit = new Fn(interposer.getFunctionAddress("slInit"), "PJ");
            slIsFeatureSupported = new Fn(interposer.getFunctionAddress("slIsFeatureSupported"), "IP");
            slGetFeatureFunction = new Fn(interposer.getFunctionAddress("slGetFeatureFunction"), "IPP");
            slGetNewFrameToken = new Fn(interposer.getFunctionAddress("slGetNewFrameToken"), "PP");
            slSetConstants = new Fn(interposer.getFunctionAddress("slSetConstants"), "PPP");
            slSetTagForFrame = new Fn(interposer.getFunctionAddress("slSetTagForFrame"), "PPPIP");
            slEvaluateFeature = new Fn(interposer.getFunctionAddress("slEvaluateFeature"), "IPPIP");

            long prefs = struct(Preferences_SIZE, Preferences_GUID, Preferences_VERSION);
            long pluginDir = MemoryUtil.memAddress(MemoryUtil.memUTF16(d.getAbsolutePath())); // wchar_t on Windows
            long paths = MemoryUtil.nmemCalloc(1, 8);
            MemoryUtil.memPutAddress(paths, pluginDir);
            File logs = new File(d, "logs");
            logs.mkdirs();
            long logDir = MemoryUtil.memAddress(MemoryUtil.memUTF16(logs.getAbsolutePath()));
            long features = MemoryUtil.nmemCalloc(1, 4);
            MemoryUtil.memPutInt(features, FEATURE_DLSS);
            long engineVersion = MemoryUtil.memAddress(MemoryUtil.memUTF8("1.0"));
            long projectId = MemoryUtil.memAddress(MemoryUtil.memUTF8("6a1b8f3e-0c47-4b5e-9d1a-7f2e5c3b9a10"));
            keep.put("prefs", prefs); keep.put("pluginDir", pluginDir); keep.put("paths", paths); keep.put("logDir", logDir);
            keep.put("features", features); keep.put("engineVersion", engineVersion); keep.put("projectId", projectId);
            MemoryUtil.memPutByte(prefs + Preferences_showConsole, (byte) 0);
            MemoryUtil.memPutInt(prefs + Preferences_logLevel, Boolean.getBoolean("betapt.nvidia.verbose") ? LOG_VERBOSE : LOG_DEFAULT);
            MemoryUtil.memPutAddress(prefs + Preferences_pathsToPlugins, paths);
            MemoryUtil.memPutInt(prefs + Preferences_numPathsToPlugins, 1);
            MemoryUtil.memPutAddress(prefs + Preferences_pathToLogsAndData, logDir);
            MemoryUtil.memPutLong(prefs + Preferences_flags, PREF_DISABLE_CL_STATE_TRACKING); // no over-the-air downloads
            MemoryUtil.memPutAddress(prefs + Preferences_featuresToLoad, features);
            MemoryUtil.memPutInt(prefs + Preferences_numFeaturesToLoad, 1);
            MemoryUtil.memPutInt(prefs + Preferences_applicationId, 0);
            MemoryUtil.memPutInt(prefs + Preferences_engine, ENGINE_CUSTOM);
            MemoryUtil.memPutAddress(prefs + Preferences_engineVersion, engineVersion);
            MemoryUtil.memPutAddress(prefs + Preferences_projectId, projectId);
            MemoryUtil.memPutInt(prefs + Preferences_renderAPI, RENDER_API_VULKAN);
            int r = slInit.call(prefs, SDK_VERSION);
            if (r != RESULT_OK) { status = "DLSS: Streamline wouldn't start (error " + r + ")"; return false; }
            // from now on every Vulkan call goes through Streamline (it hooks the instance and device it needs)
            try { VK.destroy(); } catch (Throwable ignored) {}
            VK.create(ip.getAbsolutePath());
            slStarted = true;
            status = "DLSS: Streamline started";
            return true;
        } catch (Throwable t) {
            status = "DLSS: " + t;
            return false;
        }
    }

